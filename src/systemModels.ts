export interface SystemNode {
  id: string;
  label: string;
  role: string;
  kind: Glyph;
  position: [number, number, number];
  detail: string;
  sample: string;
}
export interface SystemRoute {
  from: string;
  to: string;
  label: string;
  kind: "data" | "ack" | "replica" | "metadata";
}
export interface SystemPhase {
  title: string;
  action: string;
  detail: string;
  active: string[];
  routes: SystemRoute[];
  before: string;
  after: string;
  invariant: string;
  pressure: string;
}
export interface SystemModel {
  id: SystemId;
  name: string;
  short: string;
  category: string;
  accent: string;
  glyph: Glyph;
  description: string;
  operation: string;
  algorithm: string;
  scaling: string;
  projects: string[];
  nodes: SystemNode[];
  phases: SystemPhase[];
  fault: { node: string; label: string; effect: string; response: string };
  reference: { title: string; url: string };
}
const n = (
  id: string,
  label: string,
  role: string,
  kind: Glyph,
  x: number,
  z: number,
  detail: string,
  sample: string,
): SystemNode => ({
  id,
  label,
  role,
  kind,
  position: [x, 0, z],
  detail,
  sample,
});
const r = (
  from: string,
  to: string,
  label: string,
  kind: SystemRoute["kind"] = "data",
): SystemRoute => ({ from, to, label, kind });
const p = (
  title: string,
  action: string,
  active: string[],
  routes: SystemRoute[],
  before: string,
  after: string,
  detail: string,
  invariant: string,
  pressure: string,
): SystemPhase => ({
  title,
  action,
  active,
  routes,
  before,
  after,
  detail,
  invariant,
  pressure,
});

